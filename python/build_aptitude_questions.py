"""
Builds db/aptitude_questions_seed.sql  (the aptitude question bank).

    python python/build_aptitude_questions.py

* Numerical and many logical questions are GENERATED from templates, so every answer is computed
  by code (never typed by hand).  A fixed random seed makes the output reproducible.
* Verbal questions and some reasoning questions are hand-written in apt_handwritten.py.
* The SQL uses INSERT IGNORE + a unique hash, so importing it twice does not create duplicates.
Add your own questions by editing the templates/lists, then run this script again and re-import the SQL.
"""
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from apt_common import Bank
import apt_numerical, apt_logical, apt_handwritten

OUT = Path(__file__).resolve().parent.parent / "db" / "aptitude_questions_seed.sql"

def esc(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"

def main():
    bank = Bank(seed=2026)
    for gen in apt_numerical.ALL + apt_logical.ALL:
        gen(bank)
    apt_handwritten.generate(bank)
    counts = Counter(r["topic"] for r in bank.rows)
    lines = ["-- NexPath aptitude question bank (generated by python/build_aptitude_questions.py)",
             "-- Safe to import more than once (duplicates are ignored).", "SET NAMES utf8mb4;", "USE nexpath_db;", ""]
    cols = "(category, topic, subtopic, question, option_a, option_b, option_c, option_d, correct_answer, explanation, difficulty, q_hash)"
    for r in bank.rows:
        o = r["options"]
        vals = [r["category"], r["topic"], r["subtopic"], r["question"], o[0], o[1], o[2], o[3], r["answer"], r["explanation"], r["difficulty"], r["q_hash"]]
        lines.append(f"INSERT IGNORE INTO aptitude_questions {cols} VALUES (" + ", ".join(esc(v) for v in vals) + ");")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(bank.rows)} questions, {len(counts)} topics -> {OUT}")
    print("smallest topics:", counts.most_common()[-3:])

if __name__ == "__main__":
    main()
